#!/usr/bin/env node
/* ==========================================================================
   KZD Solutions — blog build script

   Run:  node tools/build-blog.js

   Does two jobs, both of which exist because this is a static site whose blog
   content is fetched client-side:

     1. sitemap.xml — regenerated from posts.json so it can never drift out of
        step with the content. A hand-maintained sitemap goes stale the first
        time somebody adds a post and forgets.

     2. Prerender (ON BY DEFAULT, --no-prerender to skip) — writes one real HTML
        file per post, at blog/<slug>.html, with that post's <title>,
        description, canonical, Open Graph and JSON-LD baked into the <head>.

        This is the ONLY way to get correct link previews out of the current
        setup. article.html?slug= writes its metadata with JavaScript, and the
        LinkedIn, Facebook, WhatsApp and X preview crawlers do not execute
        JavaScript — so without this every share of every article shows the same
        generic card. See the banner at the top of js/kzd-blog.js.

        The proper fix is the Next.js + Payload migration, where
        generateMetadata() emits this server-side. Treat prerendering as a
        stopgap, not a solution.
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://kzdsolutions.co.za';

function readPosts() {
  const raw = fs.readFileSync(path.join(ROOT, 'posts.json'), 'utf8');
  const data = JSON.parse(raw);
  return (data.posts || []).filter(p => p && p.slug && p.title);
}

function esc(s) {
  return String(s || '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/* -------------------------------------------------------------------------
   sitemap.xml
   ------------------------------------------------------------------------- */

const STATIC_PAGES = [
  ['', '1.0', 'weekly'],
  ['services.html', '0.9', 'monthly'],
  ['careers.html', '0.8', 'weekly'],
  ['contact.html', '0.7', 'monthly'],
  ['blog.html', '0.9', 'weekly'],
  ['hosting.html', '0.6', 'monthly'],
  ['cloud.html', '0.6', 'monthly'],
  ['VpsHosting.html', '0.6', 'monthly'],
  ['wordpress.html', '0.6', 'monthly'],
  ['accounting.html', '0.6', 'monthly'],
  ['domain-register.html', '0.5', 'monthly'],
  ['domain-transfer.html', '0.5', 'monthly'],
  ['domain-pricing.html', '0.5', 'monthly'],
  ['tld-extensions.html', '0.5', 'monthly']
];

function buildSitemap(posts) {
  const today = new Date().toISOString().slice(0, 10);
  const urls = [];

  STATIC_PAGES.forEach(([p, priority, freq]) => {
    urls.push(
`  <url>
    <loc>${SITE}/${p}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${freq}</changefreq>
    <priority>${priority}</priority>
  </url>`);
  });

  posts.forEach(post => {
    urls.push(
`  <url>
    <loc>${SITE}/blog/${esc(post.slug)}.html</loc>
    <lastmod>${post.publishedAt}</lastmod>
    <changefreq>yearly</changefreq>
    <priority>0.7</priority>
  </url>`);
  });

  const xml =
`<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-blog.js. Do not edit by hand: re-run the script
     after adding or changing a post. -->
<urlset xmlns="http://www.sitemap.org/schemas/sitemap/0.9">
${urls.join('\n')}
</urlset>
`.replace('http://www.sitemap.org', 'http://www.sitemaps.org');

  fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), xml, 'utf8');
  return STATIC_PAGES.length + posts.length;
}

/* -------------------------------------------------------------------------
   Prerender
   ------------------------------------------------------------------------- */

function prerender(posts) {
  const shell = fs.readFileSync(path.join(ROOT, 'article.html'), 'utf8');
  const outDir = path.join(ROOT, 'blog');
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir);

  posts.forEach(post => {
    const title = (post.seo && post.seo.metaTitle) || post.title;
    const desc = (post.seo && post.seo.metaDescription) || post.excerpt || '';
    const url = `${SITE}/blog/${post.slug}.html`;
    const img = `${SITE}/images/logo-black.png`;

    let s = shell;

    // Paths move up one directory once the file lives in /blog/.
    s = s.replace(/(src|href)="(?!https?:|\/\/|#|mailto:|tel:|data:)([^"]+)"/g,
                  (m, attr, p) => `${attr}="../${p}"`);

    s = s.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(title)}</title>`);
    s = s.replace(/<meta name="description" content="[^"]*">/,
                  `<meta name="description" content="${esc(desc)}">`);
    s = s.replace(/<link rel="canonical"[^>]*>/, `<link rel="canonical" href="${url}" />`);
    s = s.replace(/<meta property="og:title"[^>]*\/>/, `<meta property="og:title" content="${esc(title)}" />`);
    s = s.replace(/<meta property="og:description"[^>]*\/>/, `<meta property="og:description" content="${esc(desc)}" />`);
    s = s.replace(/<meta property="og:url"[^>]*\/>/, `<meta property="og:url" content="${url}" />`);

    const jsonld = {
      '@context': 'https://schema.org',
      '@type': 'BlogPosting',
      headline: post.title,
      description: desc,
      datePublished: post.publishedAt,
      dateModified: post.publishedAt,
      author: { '@type': 'Organization', name: post.author || 'KZD Solutions', url: SITE },
      publisher: {
        '@type': 'Organization',
        name: 'KZD Solutions',
        logo: { '@type': 'ImageObject', url: img }
      },
      mainEntityOfPage: { '@type': 'WebPage', '@id': url },
      articleSection: post.category
    };

    s = s.replace('</head>',
`        <meta property="article:published_time" content="${post.publishedAt}" />
        <meta property="article:section" content="${esc(post.category)}" />
        <script type="application/ld+json" id="kzd-jsonld-article">
${JSON.stringify(jsonld, null, 2)}
        </script>
        <!-- Pre-rendered by tools/build-blog.js. The controller still hydrates
             the body from posts.json using the slug below. -->
        <script>window.__KZD_SLUG = ${JSON.stringify(post.slug)};</script>
    </head>`);

    fs.writeFileSync(path.join(outDir, post.slug + '.html'), s, 'utf8');
  });

  return posts.length;
}

/* ------------------------------------------------------------------------- */

const posts = readPosts();
const n = buildSitemap(posts);
console.log(`sitemap.xml written — ${n} URLs (${posts.length} articles)`);

if (!process.argv.includes('--no-prerender')) {
  const m = prerender(posts);
  console.log(`prerendered ${m} article pages into blog/`);
  console.log('NOTE: these exist so link-preview crawlers see real metadata.');
  console.log('      The real fix is server-rendered metadata in Next.js —');
  console.log('      delete this script once /blog/[slug] is live there.');
}
